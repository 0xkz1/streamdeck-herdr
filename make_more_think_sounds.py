#!/usr/bin/env python3
"""考え中の音の素材を増やす。make_sounds.py と同じ合成(MATERIALS の短い打撃 → roll_burst の「ひと転がり」)。
音程のあるピン・鐘は使わない(既存と別のタイプになる)。素材を足しているだけ。

素材:
  ice     … 氷の粒: 乾いて鋭い、割れるような小さな音(彗星の欠片)
  iron    … 隕鉄: 低めの重い金属、短く鈍く鳴る
  tin     … ブリキ板: ガラガラした金属(船体のパネルを叩くような)
  crystal … 水晶の粒: 高く細かい、きらめく金属寄りの音
  brass   … 真鍮の玉: 中音の温かい金属
  plastic … プラスチックの玉: 軽く乾いた音
  basalt  … 玄武岩: 石よりさらに低く暗い
  marble  … 大理石の玉: 硬く、すこし長めに鳴る
  pearl   … 真珠の粒: 小さく硬くなめらか
  steel   … 鋼球(ベアリング): 澄んで少し長い金属
  copper  … 銅の玉: 中音のやや鈍い金属
  bone    … 骨の欠片: 乾いたカチッ
  gravel  … 砂利: 石の粒が混ざったざらつき
  porcelain … 磁器: ガラスと陶器の間
  slate   … 粘板岩: 平たい石のカツッ
  jade    … 翡翠: 澄んだ中高音の石

使い方: make_more_think_sounds.py <出力ディレクトリ> [1素材あたりの数=12]
"""
import os
import sys
import wave
import zlib

import numpy as np

import make_sounds as m

# 名前: (共鳴の高さの範囲, (倍率, 強さ, 減衰) の並び, 長さ, ざらつき)  ← MATERIALS と同じ形・同じ減衰の桁
NEW = {
    "ice":     ((3400, 6200), ((1.0, 1.0, 60),  (2.6, 0.4, 100), (4.9, 0.2, 170)),  0.16, 0.85),
    "iron":    ((700, 1400),  ((1.0, 1.0, 34),  (2.7, 0.55, 60), (4.8, 0.3, 110)),  0.34, 0.55),
    "tin":     ((2000, 3600), ((1.0, 1.0, 26),  (2.3, 0.6, 45),  (3.8, 0.4, 80)),   0.38, 0.65),
    "crystal": ((4000, 7000), ((1.0, 1.0, 40),  (2.45, 0.5, 70), (4.1, 0.3, 120)),  0.28, 0.20),
    "brass":   ((1100, 2000), ((1.0, 1.0, 48),  (2.1, 0.5, 80),  (3.7, 0.3, 140)),  0.26, 0.35),
    "plastic": ((1200, 2400), ((1.0, 1.0, 180), (1.6, 0.35, 260)),                  0.07, 0.90),
    "basalt":  ((320, 700),   ((1.0, 1.0, 290), (1.8, 0.4, 360)),                   0.08, 1.10),
    "marble":  ((1900, 3000), ((1.0, 1.0, 110), (2.4, 0.45, 170), (4.2, 0.2, 260)), 0.14, 0.55),
    "pearl":   ((2600, 4200), ((1.0, 1.0, 90),  (2.3, 0.4, 150), (4.0, 0.2, 230)),  0.12, 0.60),
    "steel":   ((2400, 4000), ((1.0, 1.0, 30),  (2.8, 0.5, 52),  (5.0, 0.3, 95)),   0.40, 0.40),
    "copper":  ((1600, 2800), ((1.0, 1.0, 52),  (2.2, 0.5, 90),  (3.9, 0.3, 150)),  0.24, 0.40),
    "bone":    ((900, 1700),  ((1.0, 1.0, 200), (2.0, 0.35, 300)),                  0.08, 0.80),
    "gravel":  ((1000, 2400), ((1.0, 0.7, 380), (1.5, 0.3, 450)),                   0.06, 1.40),
    "porcelain": ((2800, 4600), ((1.0, 1.0, 75), (2.5, 0.45, 125), (4.4, 0.2, 200)), 0.18, 0.40),
    "slate":   ((600, 1300),  ((1.0, 1.0, 160), (2.1, 0.4, 240)),                   0.11, 0.80),
    "jade":    ((1400, 2300), ((1.0, 1.0, 70),  (2.15, 0.5, 115), (3.8, 0.25, 190)), 0.20, 0.45),
}
m.MATERIALS.update(NEW)


def main():
    outdir = sys.argv[1]
    per = int(sys.argv[2]) if len(sys.argv) > 2 else 12
    os.makedirs(outdir, exist_ok=True)
    for kind in NEW:
        for i in range(per):
            r = np.random.default_rng(1000 + zlib.crc32(kind.encode()) % 997 + i)
            burst = m.roll_burst(kind, r)
            st = m.room(burst, "small")[:, : int(m.SR * (len(burst) / m.SR + 0.4))]
            pan = r.uniform(0.35, 1.0)
            st[0 if r.random() < 0.5 else 1] *= pan
            st = st / (np.abs(st).max() + 1e-9) * 0.7
            f = int(m.SR * 0.06)
            st[:, -f:] *= np.linspace(1, 0, f)
            with wave.open(os.path.join(outdir, f"{kind}-{i}.wav"), "wb") as w:
                w.setnchannels(2); w.setsampwidth(2); w.setframerate(m.SR); w.writeframes((st.T * 32767).astype("<i2").tobytes())
        print("ok", kind, per)


if __name__ == "__main__":
    main()
